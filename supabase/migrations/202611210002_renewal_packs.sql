create table if not exists public.renewal_packs (
  id uuid primary key default gen_random_uuid(),
  tenant_id text not null check (tenant_id ~ '^[a-z0-9][a-z0-9_-]{0,62}$'),
  client_user_id uuid not null references auth.users(id) on delete restrict,
  adviser_user_id uuid not null references auth.users(id) on delete restrict,
  title text not null check (char_length(title) between 1 and 120),
  status text not null default 'active'
    check (status in ('active', 'submitted', 'verified', 'revoked')),
  token_hash text not null unique check (token_hash ~ '^[0-9a-f]{64}$'),
  expires_at timestamptz not null,
  submitted_at timestamptz,
  revoked_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, tenant_id)
);

create index if not exists renewal_packs_tenant_client_idx
  on public.renewal_packs (tenant_id, adviser_user_id, client_user_id, created_at desc);
create index if not exists renewal_packs_token_hash_idx
  on public.renewal_packs (token_hash);

create table if not exists public.renewal_pack_items (
  id uuid primary key default gen_random_uuid(),
  pack_id uuid not null,
  tenant_id text not null,
  type text not null check (type in ('document', 'confirmation', 'information')),
  label text not null check (char_length(label) between 1 and 160),
  required boolean not null default true,
  status text not null default 'pending'
    check (status in ('pending', 'submitted', 'verified', 'rejected')),
  response_text text check (response_text is null or char_length(response_text) <= 2000),
  object_path text,
  rejection_reason text check (rejection_reason is null or char_length(rejection_reason) <= 500),
  updated_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  foreign key (pack_id, tenant_id)
    references public.renewal_packs (id, tenant_id) on delete restrict,
  unique (id, pack_id)
);

-- Storage paths are generated by the server as tenant/client/pack/item/random-name.
alter table public.renewal_pack_items
  add constraint renewal_pack_items_object_path_check
  check (
    object_path is null or
    (object_path !~ '(^/|\\.\\.|\\\\)' and split_part(object_path, '/', 1) = tenant_id)
  );

create table if not exists public.renewal_pack_audit (
  id bigint generated always as identity primary key,
  tenant_id text not null check (tenant_id ~ '^[a-z0-9][a-z0-9_-]{0,62}$'),
  pack_id uuid not null,
  actor_user_id uuid not null references auth.users(id) on delete restrict,
  actor_type text not null check (actor_type in ('adviser', 'client')),
  action text not null check (char_length(action) between 1 and 80),
  occurred_at timestamptz not null default now(),
  ip_address inet,
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
  foreign key (pack_id, tenant_id)
    references public.renewal_packs (id, tenant_id) on delete restrict
);

create index if not exists renewal_pack_audit_pack_time_idx
  on public.renewal_pack_audit (tenant_id, pack_id, occurred_at desc);

alter table public.renewal_packs enable row level security;
alter table public.renewal_pack_items enable row level security;
alter table public.renewal_pack_audit enable row level security;

revoke all on public.renewal_packs from public, anon, authenticated;
revoke all on public.renewal_pack_items from public, anon, authenticated;
revoke all on public.renewal_pack_audit from public, anon, authenticated;
grant select, insert, update on public.renewal_packs to service_role;
grant select, insert, update on public.renewal_pack_items to service_role;
grant select, insert on public.renewal_pack_audit to service_role;
revoke update, delete, truncate on public.renewal_pack_audit from service_role;
revoke delete, truncate on public.renewal_packs, public.renewal_pack_items from service_role;
grant usage, select on sequence public.renewal_pack_audit_id_seq to service_role;

